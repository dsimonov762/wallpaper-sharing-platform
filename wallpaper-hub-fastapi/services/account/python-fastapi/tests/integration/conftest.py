@pytest.fixture(scope="session")
def signing_key() -> rsa.RSAPrivateKey:
    return rsa.generate_private_key(public_exponent=65537, key_size=2048)


@pytest.fixture
def auth_headers(
    client: TestClient, signing_key: rsa.RSAPrivateKey
) -> Callable[..., dict[str, str]]:
    """Log in without Keycloak: `auth_headers("USER", sub=user_id)` is a valid Authorization header.

    Using this fixture swaps the running app's token validator for one that trusts a key
    generated by the test run, so these tests need the database but not Keycloak.
    """

    async def fake_jwks() -> Mapping[str, object]:
        await asyncio.sleep(0)
        jwk = json.loads(RSAAlgorithm.to_jwk(signing_key.public_key()))
        jwk.update({"kid": KEY_ID, "use": "sig", "alg": "RS256"})
        return {"keys": [jwk]}

    cast(FastAPI, client.app).state.token_validator = TokenValidator(
        JwksCache(fake_jwks), issuer=ISSUER, audience=AUDIENCE
    )

    def make(*roles: str, sub: str | None = None) -> dict[str, str]:
        claims: dict[str, Any] = {
            "sub": sub or str(uuid4()),
            "iss": ISSUER,
            "aud": AUDIENCE,
            "typ": "Bearer",
            "exp": int(time.time()) + 300,
            "realm_access": {"roles": list(roles)},
        }
        token = jwt.encode(claims, signing_key, algorithm="RS256", headers={"kid": KEY_ID})
        return {"Authorization": f"Bearer {token}"}

    return make
